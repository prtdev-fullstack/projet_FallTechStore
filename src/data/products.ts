export const bestSellers = [...products].sort((a, b) => (b.sold ?? 0) - (a.sold ?? 0));

/** Nouveautés, du plus récent au plus ancien. */
export const newArrivals = [...products].sort((a, b) => b.releasedAt.localeCompare(a.releasedAt));
