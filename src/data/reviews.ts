/** Avis d'un produit, du plus récent au plus ancien. */
export function reviewsForProduct(slug: string): Review[] {
  return reviews
    .filter((review) => review.productSlug === slug)
    .sort((a, b) => b.date.localeCompare(a.date));
}

/** Répartition des notes de 5 à 1 étoiles, pour l'histogramme de la fiche produit. */
export function ratingBreakdown(slug: string): { stars: number; count: number; percent: number }[] {
  const list = reviews.filter((review) => review.productSlug === slug);
  const total = list.length || 1;
  return [5, 4, 3, 2, 1].map((stars) => {
    const count = list.filter((review) => Math.round(review.rating) === stars).length;
    return { stars, count, percent: Math.round((count / total) * 100) };
  });
}

